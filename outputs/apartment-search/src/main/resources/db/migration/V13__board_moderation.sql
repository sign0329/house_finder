ALTER TABLE board_post ADD COLUMN hidden BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE board_comment ADD COLUMN hidden BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE board_report (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reporter_id BIGINT NOT NULL REFERENCES user_account(id),
 target_type VARCHAR(10) NOT NULL CHECK (target_type IN ('POST','COMMENT')),
 target_id BIGINT NOT NULL,
 post_id BIGINT NOT NULL,
 reason VARCHAR(500) NOT NULL,
 snapshot_title VARCHAR(120) NOT NULL,
 snapshot_body VARCHAR(10000) NOT NULL,
 status VARCHAR(12) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','HIDDEN','RESTORED','DISMISSED')),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (reporter_id,target_type,target_id)
);
CREATE INDEX idx_board_report_status_id ON board_report(status,id);
CREATE TABLE board_moderation_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id BIGINT NOT NULL REFERENCES board_report(id),
 admin_username VARCHAR(64) NOT NULL,
 action VARCHAR(10) NOT NULL CHECK (action IN ('HIDE','RESTORE','DISMISS')),
 note VARCHAR(500) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_board_moderation_report ON board_moderation_event(report_id,id);
