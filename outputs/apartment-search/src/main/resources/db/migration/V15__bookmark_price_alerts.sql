ALTER TABLE user_bookmark ADD COLUMN target_price BIGINT CHECK (target_price > 0 AND target_price <= 1000000000);
ALTER TABLE user_bookmark ADD COLUMN alert_after_trade_id BIGINT NOT NULL DEFAULT 0;
CREATE TABLE price_notification (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bookmark_id BIGINT NOT NULL REFERENCES user_bookmark(id) ON DELETE CASCADE,
 source_key VARCHAR(80) NOT NULL,
 price BIGINT NOT NULL CHECK (price > 0),
 area NUMERIC(12,4) NOT NULL,
 floor INTEGER NOT NULL,
 deal_date DATE NOT NULL,
 is_read BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(bookmark_id, source_key)
);
CREATE INDEX idx_price_notification_bookmark_id ON price_notification(bookmark_id,id);
